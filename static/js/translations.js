// Language Controller Function
function setLanguage(lang) {
    if (!emsTranslations[lang]) {
        lang = 'en';
    }
    
    localStorage.setItem('ems_language', lang);
    document.documentElement.lang = lang;
    
    // Update select dropdown value if present
    const selector = document.getElementById('language-selector');
    if (selector && selector.value !== lang) {
        selector.value = lang;
    }
    
    // Update buttons with data-lang attribute if present
    document.querySelectorAll('[data-lang-btn]').forEach(btn => {
        if (btn.getAttribute('data-lang-btn') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    const dict = emsTranslations[lang];

    // 1. Translate elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerHTML = dict[key];
        }
    });

    // 2. Translate elements with data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.placeholder = dict[key];
        }
    });

    // 3. Fallback text-replacement for common elements if data-i18n is not on the tag
    translateTextNodes(dict);
}

